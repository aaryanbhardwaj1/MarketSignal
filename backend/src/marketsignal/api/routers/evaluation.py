"""Evaluation catalog (final productization phase, developer tools): validated evaluation
artifacts served from a precomputed catalog. Dev-only router (not mounted in prod).

Read-only, no database and no model calls: everything comes from
``marketsignal.devtools.eval_catalog`` (generated by ``scripts/build_eval_catalog.py``).
"""

from __future__ import annotations

from typing import Annotated, Any

from fastapi import APIRouter, Query, Request, Response

from marketsignal.api.errors import AppError
from marketsignal.devtools import eval_catalog

router = APIRouter(prefix="/api/dev/eval", tags=["evaluation"])

_CACHE = "private, max-age=60"


def _unavailable(exc: eval_catalog.EvalCatalogUnavailableError) -> AppError:
    return AppError(503, "EVAL_CATALOG_UNAVAILABLE", str(exc))


@router.get("/catalog")
def get_catalog(request: Request, response: Response) -> Any:
    """The whole ``EvalCatalog`` (about 115 KB); ETag is the sha256 of the generated file."""
    try:
        loaded = eval_catalog.load_catalog()
    except eval_catalog.EvalCatalogUnavailableError as exc:
        raise _unavailable(exc) from exc
    if request.headers.get("if-none-match") == loaded.etag:
        return Response(status_code=304, headers={"ETag": loaded.etag, "Cache-Control": _CACHE})
    response.headers["ETag"] = loaded.etag
    response.headers["Cache-Control"] = _CACHE
    return loaded.payload


@router.get("/runs/{run_id}/items")
def get_run_items(
    run_id: str,
    offset: Annotated[int, Query(ge=0)] = 0,
    limit: Annotated[int, Query(ge=1, le=eval_catalog.MAX_PAGE_SIZE)] = 20,
    bucket: Annotated[str | None, Query(max_length=64)] = None,
) -> Any:
    """One page of ``EvalItem`` (``EvalItemsPage``); ``bucket`` filters by a failure bucket id."""
    if not eval_catalog.is_known_run(run_id):
        raise AppError(404, "EVAL_RUN_NOT_FOUND", "unknown evaluation run")
    try:
        return eval_catalog.load_items(run_id, offset=offset, limit=limit, bucket=bucket)
    except eval_catalog.EvalCatalogUnavailableError as exc:
        raise _unavailable(exc) from exc
